export function applyAccentTheme(themeName: string, forceDarkMode?: boolean) {
  const themeGroup = ACCENT_THEMES[themeName];
  if (!themeGroup) return;

  const isDark = forceDarkMode !== undefined 
    ? forceDarkMode 
    : document.documentElement.classList.contains("dark");

  const theme = isDark ? themeGroup.dark : themeGroup.light;
  const root = document.documentElement;
  Object.entries(theme).forEach(([key, val]) => {
    root.style.setProperty(key, val);
  });
}
